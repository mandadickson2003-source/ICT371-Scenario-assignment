CREATE OR REPLACE PROCEDURE event_lab.book_seats(
    p_event_id       integer,
    p_student_number text,
    p_seats          integer
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_available  integer;
    v_booking_id integer;
BEGIN
    IF p_seats <= 0 THEN
        RAISE EXCEPTION 'Seats must be positive'
            USING ERRCODE = '22023';
    END IF;
    SELECT available_seats INTO v_available
    FROM event_lab.events
    WHERE event_id = p_event_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE NOTICE 'Event % does not exist', p_event_id;
        RETURN;
    ELSIF v_available < p_seats THEN
        RAISE NOTICE 'Insufficient seats: only % available', v_available;
        RETURN;
    END IF;
    UPDATE event_lab.events
    SET available_seats = available_seats - p_seats
    WHERE event_id = p_event_id;
    INSERT INTO event_lab.bookings
        (event_id, student_number, seats, status)
    VALUES (p_event_id, p_student_number, p_seats, 'ACTIVE')
    RETURNING booking_id INTO v_booking_id;
    RAISE NOTICE 'Booking % created for student %', v_booking_id, p_student_number;
END;
$$;

