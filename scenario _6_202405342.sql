CREATE OR REPLACE PROCEDURE event_lab.show_full_events()
LANGUAGE plpgsql
AS $$
DECLARE
    v_event record;
    c_full CURSOR FOR
        SELECT event_name, available_seats
        FROM event_lab.events
        WHERE available_seats <= 5
        ORDER BY event_id;
BEGIN
    OPEN c_full;
    LOOP
        FETCH c_full INTO v_event;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Full or nearly full: % (% remaining)', v_event.event_name, v_event.available_seats;
    END LOOP;
    CLOSE c_full;
END;
$$;
