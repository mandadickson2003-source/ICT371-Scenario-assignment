CREATE OR REPLACE PROCEDURE hostel_lab.show_full_rooms()
LANGUAGE plpgsql
AS $$
DECLARE
    v_room record;
    c_full CURSOR FOR
        SELECT room_number, available_spaces
        FROM hostel_lab.hostel_rooms
        WHERE available_spaces <= 1
        ORDER BY room_id;
BEGIN
    OPEN c_full;
    LOOP
        FETCH c_full INTO v_room;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Full or nearly full: % (% remaining)', v_room.room_number, v_room.available_spaces;
    END LOOP;
    CLOSE c_full;
END;
$$;
